"""The PWLS 4.0 property-kind hierarchy: is a neutron porosity a porosity?

Energistics ships the kinds as an EPC of 3 919 `PropertyKind` parts
(`eml23_pwls40.epc`, 11 MB), each naming its parent. What the app needs of
it is the ancestry alone, so a derived table ships with the package:
``assets/pwls40_kinds.json`` = ``{title: [parent_title, quantity_class]}``,
regenerated by ``scripts/gen_pwls_kinds.py`` from the EPC. Titles are
compared lower-cased, as FESPP's `propertyKind` attribute carries them.

`relation(a, b)` answers the reconciliation's question: the same kind, one a
specialisation of the other (a descendant, "water saturation" under
"saturation"), or nothing. Siblings are deliberately NOT related: "water
saturation" and "gas saturation" share a parent and must never be set
against each other.
"""
import json
import os

_TABLE = None
_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                     "assets", "pwls40_kinds.json")


def _load():
    """``{title: (parent, quantity_class)}``, read once from the shipped
    table; empty when the file is missing or unreadable."""
    global _TABLE
    if _TABLE is None:
        try:
            with open(_PATH, encoding="utf-8") as f:
                raw = json.load(f)
            _TABLE = {str(k).strip().lower(): (
                (str(v[0]).strip().lower() if v and v[0] else None),
                (str(v[1]) if len(v) > 1 and v[1] else ""))
                for k, v in raw.items()}
        except Exception:
            _TABLE = {}
    return _TABLE


def use_table(table):
    """Swap the hierarchy (the unit tests hand a tiny one); None reloads
    the shipped table on the next call."""
    global _TABLE
    _TABLE = None if table is None else {
        str(k).strip().lower(): ((str(v[0]).strip().lower() if v and v[0] else None),
                                 (str(v[1]) if len(v) > 1 and v[1] else ""))
        for k, v in table.items()}


def known(title):
    """Whether the table knows the kind `title`."""
    return (title or "").strip().lower() in _load()


def quantity_class(title):
    """The kind's quantity class ("volume per volume", "length"...), "" when
    unknown: two kinds of different classes cannot be the same quantity."""
    entry = _load().get((title or "").strip().lower())
    return entry[1] if entry else ""


def ancestors(title):
    """``[title, parent, grandparent, …]`` lower-cased, the kind itself
    first; ``[]`` for a kind the table does not know."""
    table = _load()
    t = (title or "").strip().lower()
    if t not in table:
        return []
    out, seen = [], set()
    while t and t in table and t not in seen:
        out.append(t)
        seen.add(t)
        t = table[t][0]
    return out


def relation(a, b):
    """``(distance, how)``: ``(0, "same")``, ``(k, "a under b")`` when `a`
    is a specialisation of `b` k levels down, ``(k, "b under a")`` the other
    way; or None: unknown kinds, siblings, cousins, unrelated."""
    la, lb = ancestors(a), ancestors(b)
    if not la or not lb:
        return None
    if la[0] == lb[0]:
        return 0, "same"
    if lb[0] in la:
        return la.index(lb[0]), "a under b"
    if la[0] in lb:
        return lb.index(la[0]), "b under a"
    return None
